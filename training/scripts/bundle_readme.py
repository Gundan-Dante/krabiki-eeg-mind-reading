"""Write the model card ``<model>/README.md`` of an exported inference model, from its ``meta.json`` and one subject's files.

Example:
    python training/scripts/bundle_readme.py --model inference/model --title "final v4b" \\
        --dev "sub-01..04 mean 33.8 / 68.1 / 2.6"
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np

HEADS = {"decw": "ridge decoder, noise-whitened input", "dec": "ridge decoder, raw input",
         "pdecw": "subject-pooled ridge decoder, noise-whitened input (other subjects' training trials at weight lambda)",
         "con": "contrastive two-tower head (InfoNCE), mean over seeds"}

MEANING = {"whiteners": "per-timepoint Sigma_t^-1/2 (Ledoit-Wolf on the encoding model's out-of-fold training residuals)",
           "x_mean / x_std": "mean / std of the whitened, flattened EEG window over the subject's training trials",
           "f_mean / f_std": "mean / std of the feature over the subject's training videos (the candidates are standardized with them)",
           "B / y_mean": "ridge map and intercept at the chosen alpha (pooled members: from the weighted pooled ridge at the chosen lambda); "
                         "prediction = X @ B + y_mean",
           "seed<k>_W_e / W_v / tau": "contrastive projections of the EEG window and of the video feature (cosine in the shared space); "
                                      "tau is stored for completeness and does not enter the ranking"}


def mb(n: int) -> str:
    return f"{n / 2**20:.1f} MB"


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--model", type=Path, required=True, help="model folder with meta.json (e.g. inference/model)")
    p.add_argument("--title", required=True)
    p.add_argument("--dev", default="", help="dev result line, e.g. 'sub-01..04 mean 33.8 / 68.1 / 2.6'")
    a = p.parse_args()
    meta = json.loads((a.model / "meta.json").read_text())
    members, sw, hyper, files = meta["members"], meta["weights"], meta["hyperparameters"], meta["files"]
    subjects = sorted(int(k) for k in sw)
    same = all(sw[str(s)] == sw[str(subjects[0])] for s in subjects)
    prov = meta.get("provenance", {})
    pkgs = prov.get("packages", {})
    lines = [f"# Model files: {a.title}", "",
             f"Fitted parameters of the ensemble `{meta.get('source', '')}`, read by `inference/predict.py` (numpy + scipy, CPU). "
             "Generated by `training/scripts/export_bundle.py` from the training pipeline; nothing in this folder is edited by hand. "
             "Every file is below 50 MB so a plain `git clone` is enough (no Git LFS)." + (f" Development score: **{a.dev}**." if a.dev else ""), "",
             "## Members and weights", "", "| # | member | head | features (frames) | public model | weight" + ("" if same else " (sub-01..06)") + " |",
             "|---|---|---|---|---|---|"]
    for i, m in enumerate(members):
        wt = f"{sw[str(subjects[0])][i]:.2f}" if same else " / ".join(f"{sw[str(s)][i]:.2f}" for s in subjects)
        lines.append(f"| {i} | `{m['spec']}` | {HEADS.get(m['head'], m['head'])} | {m['features']} ({m['frames']}) | "
                     f"{', '.join(m['public_models'])} | {wt} |")
    lines += ["", f"Post-processing: test-time centering = {meta['center_test']}, CSLS k = {meta['csls_k']} (stage `{meta['csls_stage']}`), "
              "row-z-scored member similarities, weighted sum, descending stable sort. EEG: crop to 0-"
              f"{meta['max_seconds']} s, FIR zero-phase decimation x{meta['decimate_factor']}, window samples "
              f"{meta['window'][0]}:{meta['window'][1]} (100 Hz).", "",
              "### Per-subject hyperparameters (chosen by training-only cross-validation)", "",
              "| subject | member | ridge alpha | encoding alpha | lambda (pooled) |", "|---|---|---|---|---|"]
    for s in subjects:
        for m in members:
            h = hyper[f"sub-{s:02d}"][m["name"]]
            lam = f"{h['lam']:g}" if "lam" in h else ""
            lines.append(f"| {s} | `{m['name']}` | {h['dec_alpha']:g} | {h['enc_alpha']:g} | {lam} |")
    lines += ["", "## Public pretrained models behind the features", "",
              "The stimulus features were computed once with these public models (released before 2026-10-16); the features of the "
              "102 test videos are stored in `candidates/`, so inference needs none of them.", "",
              "| key | library and model | source / revision | output used |", "|---|---|---|---|"]
    for key, v in meta["public_models"].items():
        src = f"`{v['hf_repo']}` @ `{v['revision']}`" if "hf_repo" in v else v.get("weights", "")
        name = v["name"] + (f" / `{v['pretrained']}`" if "pretrained" in v else "")
        pkg = v["library"].replace("_", "-")
        lines.append(f"| {key} | {v['library']} {pkgs.get(pkg) or ''}: `{name}` | {src} | {v['output']} |")
    lines += ["", "Features computed by our own code (no external model): " + ", ".join(f"`{x}`" for x in meta["own_features"]) +
              " (hand-crafted colour / frequency / edge / motion descriptors; per-100 ms luminance, contrast, edges, motion, loudness, "
              "onset and mel-band energy).", "",
              f"Producing environment: Python {prov.get('python')}; " + ", ".join(f"{k} {v}" for k, v in pkgs.items() if v) +
              f". Training code commit: `{prov.get('code_commit')}`" + (" (working tree had local changes)" if prov.get("code_dirty") else "") + ".", "",
              "## Files", "", "```", f"{a.model.name}/",
              "  meta.json                     members, weights, options, hyperparameters, public models, SHA-256 of every file, export checks",
              "  candidates/<member>.npy       (102, D) float32 features of the test videos, row j = video 1001 + j",
              "  sub-XX/train_eeg_mean.npy     (17, 150) mean preprocessed training EEG (test-time centering)",
              "  sub-XX/<member>.npz           parameters of one member for one subject (arrays below)", "```", "",
              f"{len(files)} files, {mb(sum(f['bytes'] for f in files.values()))} in total; the largest is "
              f"`{max(files, key=lambda k: files[k]['bytes'])}` ({mb(max(f['bytes'] for f in files.values()))}).", "",
              "### Arrays in `sub-XX/<member>.npz`", "", "| member | arrays (shape) |", "|---|---|"]
    for m in members:
        with np.load(a.model / f"sub-{subjects[0]:02d}" / f"{m['name']}.npz") as z:
            lines.append(f"| `{m['name']}` | " + ", ".join(f"`{k}` {tuple(z[k].shape)}" for k in z.files) + " |")
    lines += ["", "| array | meaning |", "|---|---|"] + [f"| `{k}` | {v} |" for k, v in MEANING.items()]
    lines += ["", "## Export checks", "",
              "`export_bundle.py` refits every member from the training recordings and compares the result with the live pipeline and "
              "with the similarity matrices cached by `training/scripts/ensemble.py`: largest absolute difference over all "
              f"{len(meta['checks'])} member fits = {max((c['live_vs_cached_max_abs'] or 0.0) for c in meta['checks'].values()):.2g}."]
    (a.model / "README.md").write_text("\n".join(lines) + "\n")
    print(f"wrote {a.model / 'README.md'}")


if __name__ == "__main__":
    main()
